// Helpers: every cell is cut out of a lifted span (never retyped). `norm` collapses the transcript's line breaks /
// trailing double spaces so the regexes read the printed row as one line; the stored quote stays the raw span.
// ---------------------------------------------------------------------------
/** Markdown escapes of the transcript ("\-", "\>", "\<", "\*", "\=", "\.") → the printed character (split/join, never String.replace). */
export function deMd(s: string): string {
  return s.split('\\-').join('-').split('\\>').join('>').split('\\<').join('<').split('\\*').join('*').split('\\=').join('=').split('\\.').join('.');
}
/** Whitespace-collapsed, markdown-unescaped view of a lifted span (for the regexes and display fragments; the stored quote stays raw). */
export function norm(s: string): string {
  return deMd(s.replace(/\s+/g, ' ').trim());
}
/** The substring of a lifted span from `start` up to (not including) `end` (or to the end of the span), whitespace-collapsed. */
export function frag(span: string, start: string, end?: string): string {
  const n = norm(span);
  const i = n.indexOf(start);
  if (i < 0) throw new Error(`fragment start not found: ${start}`);
  const j = end ? n.indexOf(end, i) : -1;
  if (end && j < 0) throw new Error(`fragment end not found: ${end}`);
  return (j < 0 ? n.slice(i) : n.slice(i, j)).trim();
}
/** A printed German number ("0,60", "3.600", "1,5", "280") → number (thousands dot, decimal comma). */
export function deNum(s: string): number {
  const n = Number(s.replace(/\./g, '').replace(',', '.'));
  if (!Number.isFinite(n)) throw new Error(`not a printed number: ${s}`);
  return n;
}
/** The first regex match group of a span (whitespace-collapsed) — throws when the printed text does not carry it. */
function pick(span: string, re: RegExp, what: string): string {
  const m = norm(span).match(re);
  if (!m) throw new Error(`${what}: not found in span "${norm(span).slice(0, 60)}…"`);
  return m[1];
}
/** All matches of a global regex over a span (whitespace-collapsed). */
function all(span: string, re: RegExp): RegExpMatchArray[] {
  return [...norm(span).matchAll(re)];
}
/** A Tab.-1 row "… ≤ 1:3 ≤ 33 %" → { m: 3, pct: 33 } (the "1:m" denominator and the printed percentage). */
export function slope(span: string): { m: number; pct: number } {
  const n = norm(span);
  const mm = n.match(/≤ 1:([\d,]+) ≤ (\d+) %/);
  if (!mm) throw new Error(`Tab. 1 slope cells not found: ${n}`);
  return { m: deNum(mm[1]), pct: Number(mm[2]) };
}
/** The printed row label of a Tab.-1 row: the text between the row number and the "≤ 1:" cell. */
function tab1Label(span: string): string {
  return norm(span).replace(/^\d+ /, '').replace(/ ≤ 1:.*$/, '').trim();
}

