/** The substring of a lifted span from `start` up to (not including) `end` (or to the end of the span). */
export function frag(span: string, start: string, end?: string): string {
  const i = span.indexOf(start);
  if (i < 0) throw new Error(`fragment start not found: ${start}`);
  const j = end ? span.indexOf(end, i) : -1;
  if (end && j < 0) throw new Error(`fragment end not found: ${end}`);
  return (j < 0 ? span.slice(i) : span.slice(i, j)).trim();
}
/** The cells of one printed `\hline a & b & c \\` row (LaTeX row → trimmed cell strings). */
export function cells(row: string): string[] {
  return row.replace(/^\\hline\s*/, '').replace(/\s*\\\\\s*$/, '').split('&').map((c) => c.trim()); // empty printed cells stay ''
}
/** A printed German number ("5.180", "1.177", "0,1", "30") → number (thousands dot, decimal comma). */
export function deNum(s: string): number {
  const n = Number(s.replace(/\./g, '').replace(',', '.'));
  if (!Number.isFinite(n)) throw new Error(`not a printed number: ${s}`);
  return n;
}
/**
 * A printed mathpix cell → plain text for display (review fix round 1): `$…$` delimiters dropped, `\mathrm{x}` → x,
 * `~` (LaTeX thin space) dropped, `^{3}` → ³, spaces around `/` collapsed, whitespace normalised. Mechanical and
 * lossless for the Tab.-14 cells; the raw printed cell stays beside it (`konz_gedruckt`) and in the row quote.
 */
export function deLatex(s: string): string {
  return s.replace(/\$/g, '').replace(/\\mathrm\{([^}]*)\}/g, '$1').replace(/~/g, '').replace(/\^\{3\}/g, '³').replace(/\s*\/\s*/g, '/').replace(/\s+/g, ' ').trim();
}
/** The `N` of a printed "N-fache Wurfweite" cell; an empty printed cell → null (never inferred). */
export function fache(cell: string): number | null {
  if (cell === '') return null;
  const m = cell.match(/(\d)-fache Wurfweite/);
  if (!m) throw new Error(`not a printed "N-fache Wurfweite" cell: ${cell}`);
  return Number(m[1]);
}

