/**
 * Section extraction from the raw norm-text markdown.
 *
 * The source markdown for DWA standards (e.g. `data/norm-text/DWA-A-138-1.md`)
 * is a pandoc/LaTeX dump where headings appear as
 *   \section*{N Title}, \subsection*{N.M Title}, \subsection*{N.M.K Title}, ...
 * and free-form glossary entries like
 *   \section*{Grundwasser}
 * also use the `\section*` macro but without a numeric prefix.
 *
 * The Wizard stores `clause_reference` strings like `§5.3.3.5`, `§6.4.2`,
 * `§5.2.3.2`, `Anh. A`, `Anhang A`, `Tab. 2`. Engineers must be able to click
 * one of those references and see the EXACT corresponding section of the norm.
 *
 * Source-faithfulness is non-negotiable:
 *   - If a clause does not match any heading exactly, return `{ found: false }`.
 *   - Never approximate: returning the wrong section would mislead the engineer
 *     about what the standard actually says.
 *
 * The matcher knows about three shapes:
 *   - `§N(.N)*`                  → numbered heading like `5`, `5.1`, `5.3.3.5`
 *   - `Anh. X` / `Anhang X`      → appendix heading prefixed `Anhang X`
 *   - `Tab. N` / `Tabelle N`     → tables aren't headings → `{ found: false }`.
 *
 * The source markdown for VSME (`data/norm-text/VSME.md`, generated by
 * `scripts/vsme/convert-norm-text.ts` from the EFRAG VSME Standard PDF) uses
 * plain ATX headings instead of LaTeX macros:
 *   ## B1 — Basis for preparation
 * `parseHeadings` recognises both shapes; the number/appendix classification
 * that follows runs identically on the heading's inner text regardless of
 * which macro produced it (VSME module headings simply don't match either
 * pattern, so they classify the same way unnumbered glossary headings do —
 * that's fine, because VSME clause lookups use the separate `paragraph`
 * query kind below, not the numbered/appendix path).
 *
 * VSME clause references (`clause_reference` values like `VSME B3 para 30`)
 * address a PARAGRAPH inside a module's disclosure-requirement text, not a
 * heading. `extractParagraph` below locates the module's (flush-left,
 * first-occurrence) ATX heading and slices out the one numbered paragraph —
 * same non-approximating contract as `extractSection`: no match anywhere →
 * `{ found: false }`.
 */

export type SectionMatch =
  | { found: true; title: string; markdown: string }
  | { found: false };

type Heading = {
  /** Line index where the heading appears (0-based). */
  line: number;
  /** The full markdown source line including the macro. */
  raw: string;
  /** The text inside the heading macro, e.g. `5.3.3.5 Berechnung Zuflüsse …`. */
  inner: string;
  /** The numeric prefix (e.g. `5.3.3.5`) if the inner starts with one, else null. */
  number: string | null;
  /** Heading depth derived from the section number (number of dot-segments).
   *  For Appendix headings (`Anhang X …`) depth is 1. For unnumbered glossary
   *  headings (`\section*{Grundwasser}`) depth is null — they don't terminate
   *  numbered sections. */
  depth: number | null;
  /** True iff this is an `Anhang X …` heading (appendix). */
  isAppendix: boolean;
};

const HEADING_RE = /^\\(section|subsection|subsubsection)\*\{([\s\S]*?)\}\s*$/;
/** ATX heading (VSME.md and any future ATX-sourced norm-text doc): `## Title`. */
const ATX_HEADING_RE = /^(#{1,6})\s+(.*)$/;
const NUMBER_PREFIX_RE = /^(\d+(?:\.\d+)*)(?:\s|$)/;
const APPENDIX_PREFIX_RE = /^Anhang\s+([A-Z])(?:\s|$|\.|,)/;

/**
 * Parse all headings from a markdown source. Returns headings in source order.
 *
 * Multi-line `\section*{ ... }` blocks (where the macro spans more than one
 * line) are joined back together so the heading regex sees the full title.
 * That's not the common case in our source but it does occur — e.g. the
 * `\section*{Versickerungs-Expert \\ Software zum Arbeitsblatt DWA-A 138-1}`
 * stretches over two lines.
 */
export function parseHeadings(source: string): Heading[] {
  const lines = source.split('\n');
  const headings: Heading[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const isLatexMacroLine =
      line.startsWith('\\section*{') || line.startsWith('\\subsection*{') || line.startsWith('\\subsubsection*{');
    const atxMatch = !isLatexMacroLine ? ATX_HEADING_RE.exec(line) : null;

    // Quick filter: only investigate lines starting with a section macro or
    // an ATX heading marker.
    if (!isLatexMacroLine && !atxMatch) {
      continue;
    }

    let inner: string;
    let j = i;
    /** Fallback depth for a heading whose inner text has neither a numeric
     *  nor an `Anhang` prefix. LaTeX-sourced glossary headings keep the
     *  existing `null` (unchanged behaviour); ATX-sourced headings (e.g.
     *  VSME module headings `## B1 — …`) use the ATX marker's `#`-count
     *  instead, per the ATX heading contract. */
    let unnumberedFallbackDepth: number | null;

    if (isLatexMacroLine) {
      // Collect lines until the closing `}` so multi-line headings stay whole.
      // We count braces conservatively (no quoting subtlety needed for our source).
      let joined = line;
      let braceDepth = countBraceDelta(line);
      while (braceDepth > 0 && j < lines.length - 1) {
        j++;
        joined += '\n' + lines[j];
        braceDepth += countBraceDelta(lines[j]);
      }
      const m = HEADING_RE.exec(joined.replace(/\n/g, ' '));
      if (!m) continue;
      inner = m[2].trim();
      unnumberedFallbackDepth = null;
    } else {
      // ATX heading — single line, no multi-line joining needed.
      inner = atxMatch![2].trim();
      unnumberedFallbackDepth = atxMatch![1].length;
    }

    const numMatch = NUMBER_PREFIX_RE.exec(inner);
    const appendixMatch = APPENDIX_PREFIX_RE.exec(inner);

    if (numMatch) {
      const number = numMatch[1];
      const numDepth = number.split('.').length;
      headings.push({
        line: i,
        raw: line,
        inner,
        number,
        depth: numDepth,
        isAppendix: false,
      });
    } else if (appendixMatch) {
      headings.push({
        line: i,
        raw: line,
        inner,
        number: null,
        depth: 1,
        isAppendix: true,
      });
    } else {
      headings.push({
        line: i,
        raw: line,
        inner,
        number: null,
        depth: unnumberedFallbackDepth,
        isAppendix: false,
      });
    }

    i = j; // skip lines consumed by the multi-line title
  }

  return headings;
}

function countBraceDelta(s: string): number {
  let d = 0;
  for (const ch of s) {
    if (ch === '{') d++;
    else if (ch === '}') d--;
  }
  return d;
}

/**
 * Parse a clause reference into a structured query.
 *
 * Accepted shapes (source-faithful — we only match what the engineer wrote):
 *   - `§5`, `§5.3`, `§5.3.3.5`
 *   - `5.3.3.5`              (bare number, same intent as §-prefixed)
 *   - `Anh. A`, `Anhang A`
 *   - `VSME B3 para 30`, `VSME B1 para 24(a)`, `VSME C9 para 65`
 *     (a lettered sub-item like `24(a)` still resolves to the whole
 *     paragraph `24` — VSME.md doesn't sub-address lettered sub-items, so we
 *     match the paragraph NUMBER and return its full text, sub-items
 *     included)
 *
 * Anything else (`Tab. 2`, `Bild 7`, comma-separated lists like `§5.1.1, §5.2`)
 * returns `null` — the caller will surface `{ found: false }`.
 */
export type ClauseQuery =
  | { kind: 'numbered'; number: string }
  | { kind: 'appendix'; letter: string }
  | { kind: 'paragraph'; module: string; para: string };

export function parseClauseReference(clauseRef: string): ClauseQuery | null {
  const trimmed = clauseRef.trim();
  if (!trimmed) return null;

  // §N(.N)* — strip optional leading § and optional spaces.
  const numMatch = /^§?\s*(\d+(?:\.\d+)*)\s*$/.exec(trimmed);
  if (numMatch) {
    return { kind: 'numbered', number: numMatch[1] };
  }

  // Anh. A / Anhang A — single uppercase letter, optionally followed by `.N`
  // (we don't support sub-clauses of an appendix yet; match the whole appendix).
  const apMatch = /^(?:Anh\.?|Anhang)\s+([A-Z])(?:\b|$)/.exec(trimmed);
  if (apMatch) {
    return { kind: 'appendix', letter: apMatch[1] };
  }

  // VSME B1 para 24(a) / VSME B3 para 30 / VSME C9 para 65 — module code
  // (B or C followed by 1-2 digits) plus a paragraph number. A trailing
  // lettered sub-item, e.g. `(a)`, is accepted but not captured: we resolve
  // to the whole paragraph, sub-items included.
  const pMatch = /^VSME\s+([BCD]\d{1,2})\s+para\s+(\d+)/i.exec(trimmed);
  if (pMatch) {
    return { kind: 'paragraph', module: pMatch[1].toUpperCase(), para: pMatch[2] };
  }

  return null;
}

/**
 * Locate and extract the section body for a clause reference.
 *
 * Returns the heading's title text and the markdown body (everything between
 * the heading line and the next heading of equal or higher rank — i.e. a
 * heading that would terminate this section in the source's outline).
 *
 * What counts as "equal or higher rank":
 *   - For a numbered heading at depth D, a sibling/parent terminator is any
 *     numbered heading at depth ≤ D, OR any appendix heading (`Anhang X …`).
 *   - For an appendix heading (depth 1), a terminator is the next top-level
 *     numbered heading or appendix heading. (In our DWA-A 138-1 source the
 *     appendices sit after the body, so the next top-level heading after
 *     `Anhang A` is `Anhang B`, then `Anhang C`, etc.)
 *
 * Unnumbered glossary headings (`\section*{Grundwasser}`) are NOT terminators
 * — they're sub-entries that live inside `§3.1 Definitionen`. Treating them
 * as boundaries would chop the parent section into one-paragraph slivers and
 * hide the rest of the definitions from the reader.
 */
export function extractSection(source: string, clauseRef: string): SectionMatch {
  const query = parseClauseReference(clauseRef);
  if (!query) return { found: false };

  // Normalize CRLF -> LF ONCE, here, at the single production entry point.
  // Both the LaTeX heading regex (HEADING_RE) and the ATX heading regex
  // (ATX_HEADING_RE) are anchored with `$` against a single line (no `m`
  // flag) after `source.split('\n')`; if a line still carries a trailing
  // `\r` (which happens whenever the source file was materialized with
  // CRLF line endings — e.g. Windows checkouts of a repo without a
  // `.gitattributes` pin), `.` in `(.*)$`/`\}\s*$` cannot consume the `\r`
  // and the heading fails to match entirely. Normalizing here, before the
  // source is handed to `parseHeadings` or split into `lines`, means every
  // downstream consumer (including `extractParagraph`) sees LF-only text
  // and behaves byte-identically to true-LF input.
  const normalizedSource = source.replace(/\r\n/g, '\n');

  const headings = parseHeadings(normalizedSource);
  const lines = normalizedSource.split('\n');

  if (query.kind === 'paragraph') {
    return extractParagraph(normalizedSource, headings, query.module, query.para);
  }

  // Locate the matching heading.
  let matchIdx = -1;
  for (let i = 0; i < headings.length; i++) {
    const h = headings[i];
    if (query.kind === 'numbered' && h.number === query.number) {
      matchIdx = i;
      break;
    }
    if (query.kind === 'appendix' && h.isAppendix) {
      // The appendix inner is e.g. "Anhang A (normativ) Bestimmung …" — extract
      // the letter and compare. The APPENDIX_PREFIX_RE captured it already, so
      // re-run for safety on the heading inner.
      const m = APPENDIX_PREFIX_RE.exec(h.inner);
      if (m && m[1] === query.letter) {
        matchIdx = i;
        break;
      }
    }
  }
  if (matchIdx === -1) return { found: false };

  const matched = headings[matchIdx];

  // Find the terminator: the next heading at equal or higher rank.
  const matchedDepth = matched.depth; // null only for non-matchable kinds; here always set
  let endLine = lines.length;
  for (let i = matchIdx + 1; i < headings.length; i++) {
    const h = headings[i];
    if (matched.isAppendix) {
      // Terminate at next appendix heading or next top-level numbered heading.
      if (h.isAppendix) {
        endLine = h.line;
        break;
      }
      if (h.depth === 1) {
        endLine = h.line;
        break;
      }
      continue;
    }
    // Numbered match: terminate at any numbered heading with depth ≤ matchedDepth,
    // OR at any appendix heading (appendices end the body of the standard).
    if (h.isAppendix) {
      endLine = h.line;
      break;
    }
    if (h.depth !== null && matchedDepth !== null && h.depth <= matchedDepth) {
      endLine = h.line;
      break;
    }
  }

  // Body: lines AFTER the heading line up to (but not including) endLine.
  const bodyLines = lines.slice(matched.line + 1, endLine);
  // Trim trailing blank lines for tidier rendering.
  while (bodyLines.length > 0 && bodyLines[bodyLines.length - 1].trim() === '') {
    bodyLines.pop();
  }
  // Trim leading blank lines too.
  while (bodyLines.length > 0 && bodyLines[0].trim() === '') {
    bodyLines.shift();
  }

  return {
    found: true,
    title: matched.inner,
    markdown: bodyLines.join('\n'),
  };
}

/** A body paragraph's leading number, e.g. `24.` — must start the line
 *  (optional leading whitespace tolerated defensively, though VSME.md's
 *  paragraph numbers are flush-left). */
const ANY_PARA_START_RE = /^\s*\d+\.\s/;

/**
 * Locate paragraph `para` inside module `module`'s heading section.
 *
 * "The module's heading" means the FIRST heading in source order whose
 * inner text starts with the module code on a word boundary — this is
 * deliberate, not an oversight: `beware B1 vs B11` — matching `B1` against
 * heading text `B11 – Convictions …` must fail, so the module code is
 * compared with a `\b` word-boundary regex, not a plain string prefix.
 *
 * For VSME.md specifically, only the module's DISCLOSURE heading (printed
 * pages 8-14) is marked as an ATX heading; the module's GUIDANCE recap
 * heading (printed pages 15-47) is deliberately left unmarked by the
 * converter (see `scripts/vsme/convert-norm-text.ts`). So "the module's
 * heading" resolves to exactly one heading per module here, and a paragraph
 * that only exists in the guidance narrative correctly falls through to
 * `{ found: false }` — the module doctrine (this file's header comment):
 * never approximate to the module heading's section.
 *
 * Within that heading's span (from the heading to the next heading of any
 * kind, or end of file), the target paragraph is the line matching
 * `^<para>\.\s` through the line before the NEXT numbered-paragraph line
 * (or the end of the span). A paragraph that isn't found within the span
 * returns `{ found: false }` — never the module heading's own text as a
 * fallback.
 */
function extractParagraph(source: string, headings: Heading[], module: string, para: string): SectionMatch {
  const lines = source.split('\n');
  const moduleRe = new RegExp('^' + module + '\\b');
  const paraStartRe = new RegExp('^\\s*' + para + '\\.\\s');

  for (let i = 0; i < headings.length; i++) {
    const h = headings[i];
    if (!moduleRe.test(h.inner)) continue;

    const spanEnd = i + 1 < headings.length ? headings[i + 1].line : lines.length;
    const spanLines = lines.slice(h.line + 1, spanEnd);

    let startIdx = -1;
    for (let k = 0; k < spanLines.length; k++) {
      if (paraStartRe.test(spanLines[k])) {
        startIdx = k;
        break;
      }
    }
    if (startIdx === -1) continue; // not in this module heading's span — try the next occurrence, if any

    let endIdx = spanLines.length;
    for (let k = startIdx + 1; k < spanLines.length; k++) {
      if (ANY_PARA_START_RE.test(spanLines[k])) {
        endIdx = k;
        break;
      }
    }

    const bodyLines = spanLines.slice(startIdx, endIdx);
    while (bodyLines.length > 0 && bodyLines[bodyLines.length - 1].trim() === '') {
      bodyLines.pop();
    }

    return {
      found: true,
      title: h.inner,
      markdown: bodyLines.join('\n'),
    };
  }

  return { found: false };
}
