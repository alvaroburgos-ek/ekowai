/**
 * Converts a `pdftotext -layout` dump of the VSME Standard PDF into
 * `data/norm-text/VSME.md` for the split-view norm-text reader
 * (`getNormSection` / `extractSection` in `src/lib/norm-text/`).
 *
 * Source: `VSME Standard.pdf` (EFRAG, 66 printed pages, page numbers in the
 * PDF's own footer run 1..66 with NO offset — printed page N is physical
 * page N).
 *
 * Usage (PowerShell — WSL is blind to the Desktop folder the PDF lives in):
 *   pdftotext -layout "C:\Users\Ekowai\Desktop\environmental-reporting service\01_Referenz\VSME Standard.pdf" <raw.txt>
 *   pnpm tsx scripts/vsme/convert-norm-text.ts <raw.txt>
 *
 * What this does (and nothing else):
 *   1. Strips the running footer ("Page N of 66") and running header
 *      ("VSME Standard") that repeat on every page.
 *   2. Promotes the FIRST occurrence of each module's disclosure heading
 *      (`B1 – Basis for preparation` … `C9 – Gender diversity ratio in the
 *      governance body`, flush-left in the source — these are the
 *      "Basic Module" / "Comprehensive Module" disclosure-requirement
 *      headings on printed pages 8-14) to an ATX heading:
 *      `## B1 — Basis for preparation`.
 *
 *      The SECOND occurrence of each module code (the recap heading at the
 *      top of the corresponding "… Guidance" narrative, printed pages
 *      15-47) is deliberately left as plain body text, unmarked. This is
 *      not a bug: `clause_reference` values like `VSME B3 para 30` address
 *      the enforceable disclosure requirement, not the guidance narrative,
 *      and paragraph numbers are NOT unique to a module (they're global
 *      1..~244 across the whole document) — so only the disclosure
 *      section's headings are meaningful section boundaries for paragraph
 *      lookup. A query for a paragraph that only exists in the guidance
 *      narrative correctly falls through to `{ found: false }` rather than
 *      approximating.
 *   3. Everything else — including all body paragraphs, sub-item letters,
 *      the Table of Contents, appendix text, footnotes, and the guidance
 *      narrative's repeated module-code lines — passes through verbatim,
 *      line for line.
 *
 * Deterministic: no timestamps, no environment-dependent output. Running
 * this twice on the same input byte-for-byte produces identical output.
 *
 * Read-only downstream: `data/norm-text/VSME.md` is generated output.
 * Never hand-edit it — re-run this script from a fresh `pdftotext -layout`
 * dump instead.
 */
import fs from 'node:fs';
import path from 'node:path';

const PROVENANCE_HEADER =
  '<!-- generated by scripts/vsme/convert-norm-text.ts from "VSME Standard.pdf", pdftotext -layout, 66pp, offset 0 -->';

/** Running footer, e.g. "Page 8 of 66". Matched against the TRIMMED line. */
const FOOTER_RE = /^Page \d+ of 66$/;

/** Running header. Matched against the TRIMMED line. */
const HEADER_RE = /^VSME Standard$/;

/**
 * A module disclosure/guidance heading, e.g. "B1 – Basis for preparation" or
 * "C9 – Gender diversity ratio in the governance body". These are flush-left
 * in the source (no leading whitespace) — every other line that happens to
 * start with a module code (Table of Contents entries, in-body
 * cross-references like "…required under\n    B3 – Energy and greenhouse
 * gas emissions.") is indented, so anchoring at true column 0 (matched
 * against the RAW, un-trimmed line) is what tells them apart.
 */
const MODULE_HEADING_RE = /^([BC]\d{1,2})\s+[–—-]\s+(.+)$/;

/** A body paragraph's leading number, e.g. "24." — also flush-left. */
const PARA_START_RE = /^\d+\.\s/;

/**
 * A handful of the longer module headings wrap onto a second physical line
 * in the `-layout` extraction (e.g. B2, C2). Both continuation lines are
 * themselves flush-left and start with a lowercase letter, so that's the
 * join heuristic.
 */
function isWrapContinuation(nextRaw: string | undefined): boolean {
  if (nextRaw === undefined) return false;
  const trimmed = nextRaw.trim();
  if (!trimmed) return false;
  if (FOOTER_RE.test(trimmed) || HEADER_RE.test(trimmed)) return false;
  if (MODULE_HEADING_RE.test(nextRaw)) return false;
  if (PARA_START_RE.test(nextRaw)) return false;
  return /^[a-z]/.test(trimmed);
}

export function convert(raw: string): string {
  const normalized = raw.replace(/\r\n/g, '\n').replace(/\f/g, '');
  const rawLines = normalized.split('\n');

  const kept: string[] = [];
  const emittedModules = new Set<string>();

  for (let i = 0; i < rawLines.length; i++) {
    const line = rawLines[i];
    const trimmed = line.trim();

    if (FOOTER_RE.test(trimmed)) continue;
    if (HEADER_RE.test(trimmed)) continue;

    const m = MODULE_HEADING_RE.exec(line);
    if (m && !emittedModules.has(m[1])) {
      let title = m[2].trim();
      if (isWrapContinuation(rawLines[i + 1])) {
        title = `${title} ${rawLines[i + 1].trim()}`;
        i++;
      }
      emittedModules.add(m[1]);
      kept.push(`## ${m[1]} — ${title}`);
      continue;
    }

    kept.push(line);
  }

  // Trim leading/trailing blank runs for a tidy file; internal blank lines
  // are left exactly as the source produced them.
  while (kept.length > 0 && kept[0].trim() === '') kept.shift();
  while (kept.length > 0 && kept[kept.length - 1].trim() === '') kept.pop();

  return `${PROVENANCE_HEADER}\n\n${kept.join('\n')}\n`;
}

function main() {
  const inputPath = process.argv[2];
  if (!inputPath) {
    console.error('Usage: pnpm tsx scripts/vsme/convert-norm-text.ts <pdftotext-layout-output.txt>');
    process.exit(1);
  }
  const raw = fs.readFileSync(inputPath, 'utf8');
  const md = convert(raw);
  const outPath = path.join(process.cwd(), 'data', 'norm-text', 'VSME.md');
  fs.writeFileSync(outPath, md, 'utf8');
  const moduleHeadings = (md.match(/^## /gm) ?? []).length;
  console.log(`Wrote ${outPath}: ${md.split('\n').length} lines, ${moduleHeadings} module headings.`);
}

main();
