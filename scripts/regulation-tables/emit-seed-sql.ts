import { writeFileSync } from 'node:fs';
import { SEED_BUILDERS } from '../../src/lib/eval/regulation-tables-seed-index';
import type { RegulationTable } from '../../src/lib/eval/regulation-tables';

/**
 * Slug → seed builder + migration file stamp (Plan 3 Task 0). The map itself
 * lives in the pure module `src/lib/eval/regulation-tables-seed-index.ts` so
 * the deploy-before-seed fallback (`regulation-tables-fallback.ts`) reads the
 * same set; it is re-exported here for the emitter's callers. Each Plan-3
 * standard task appends one line THERE, never here.
 */
export { SEED_BUILDERS };

const q = (s: string | null) => (s == null ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
const j = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const arr = (a: string[]) => `ARRAY[${a.map((x) => q(x)).join(',')}]::text[]`;
const tableWhere = (t: RegulationTable) => `standard_code = ${q(t.standard_code)} AND edition = ${q(t.edition)} AND table_code = ${q(t.table_code)}`;
const UNVERIFIED = 'imported_unverified';

/** The forward statements for one table: header upsert + one row upsert per row (verification_status is insert-only on conflict). */
function upStatements(t: RegulationTable): string[] {
  const out: string[] = [];
  out.push(`INSERT INTO regulation_tables (standard_code, edition, table_code, title_de, clause_reference, page_ref, key_columns, value_columns, override_policy, override_quote, verification_status)
VALUES (${q(t.standard_code)}, ${q(t.edition)}, ${q(t.table_code)}, ${q(t.title_de)}, ${q(t.clause_reference)}, ${q(t.page_ref)}, ${arr(t.key_columns)}, ${j(t.value_columns)}, ${q(t.override_policy)}, ${q(t.override_quote)}, ${q(t.verification_status)})
ON CONFLICT (standard_code, edition, table_code) DO UPDATE SET title_de = EXCLUDED.title_de, clause_reference = EXCLUDED.clause_reference, page_ref = EXCLUDED.page_ref, key_columns = EXCLUDED.key_columns, value_columns = EXCLUDED.value_columns, override_policy = EXCLUDED.override_policy, override_quote = EXCLUDED.override_quote;`);
  for (const r of t.rows) {
    out.push(`INSERT INTO regulation_table_rows (table_id, row_key, keys, group_label, label_de, order_index, row_values, verbatim_quote)
SELECT id, ${q(r.row_key)}, ${j(r.keys)}, ${q(r.group_label)}, ${q(r.label_de)}, ${r.order_index}, ${j(r.values)}, ${q(r.verbatim_quote)} FROM regulation_tables WHERE ${tableWhere(t)}
ON CONFLICT (table_id, row_key) DO UPDATE SET keys = EXCLUDED.keys, group_label = EXCLUDED.group_label, label_de = EXCLUDED.label_de, order_index = EXCLUDED.order_index, row_values = EXCLUDED.row_values, verbatim_quote = EXCLUDED.verbatim_quote;`);
  }
  // Plan 3 Task 1: a builder that lifted every row (md_verified) upgrades a still-unverified prod header — never
  // downgrades and never touches an engineer-verified table (the header upsert deliberately leaves the status alone).
  if (t.verification_status !== UNVERIFIED) {
    out.push(`UPDATE regulation_tables SET verification_status = ${q(t.verification_status)} WHERE ${tableWhere(t)} AND verification_status = ${q(UNVERIFIED)};`);
  }
  return out;
}

export type EmitSeedOptions = {
  /**
   * The tables of the builder this set SUPERSEDES (same standard, earlier slug). The rollback then restores that
   * earlier state instead of deleting everything: status upgrades reverted, tables the earlier set lacks deleted,
   * rows the earlier set lacks deleted, and the earlier set's own upserts re-emitted verbatim.
   */
  supersedes?: RegulationTable[];
};

export function emitSeedSql(tables: RegulationTable[], opts: EmitSeedOptions = {}): { up: string; down: string } {
  const up: string[] = ['-- Generated by scripts/regulation-tables/emit-seed-sql.ts — do not hand-edit; regenerate.', 'BEGIN;'];
  const down: string[] = ['BEGIN;'];
  const prior = new Map((opts.supersedes ?? []).map((t) => [`${t.standard_code}|${t.edition}|${t.table_code}`, t]));
  for (const t of tables) up.push(...upStatements(t));
  for (const t of tables) {
    const p = prior.get(`${t.standard_code}|${t.edition}|${t.table_code}`);
    if (!p) { down.push(`DELETE FROM regulation_tables WHERE ${tableWhere(t)};`); continue; }
    if (t.verification_status !== UNVERIFIED) {
      down.push(`UPDATE regulation_tables SET verification_status = ${q(UNVERIFIED)} WHERE ${tableWhere(t)} AND verification_status = ${q(t.verification_status)};`);
    }
    const keep = p.rows.map((r) => r.row_key);
    down.push(`DELETE FROM regulation_table_rows r USING regulation_tables t WHERE r.table_id = t.id AND t.${tableWhere(t).replace(/ AND /g, ' AND t.')}${keep.length ? ` AND r.row_key NOT IN (${keep.map(q).join(', ')})` : ''};`);
  }
  if (opts.supersedes) {
    down.push('-- Re-emit the superseded set verbatim (restores its headers, columns, rows and quotes).');
    for (const p of opts.supersedes) down.push(...upStatements(p));
  }
  up.push('COMMIT;'); down.push('COMMIT;');
  return { up: up.join('\n') + '\n', down: down.join('\n') + '\n' };
}

/** `emitSeedSql` for a registered slug, wiring the `supersedes` builder from the map. */
export function emitSeedSqlFor(slug: string): { up: string; down: string } {
  const b = SEED_BUILDERS[slug];
  if (!b) throw new Error(`unknown seed slug ${JSON.stringify(slug)} — known: ${Object.keys(SEED_BUILDERS).join(', ')}`);
  const sup = b.supersedes ? SEED_BUILDERS[b.supersedes] : undefined;
  if (b.supersedes && !sup) throw new Error(`seed slug ${slug} supersedes unknown slug ${JSON.stringify(b.supersedes)}`);
  return emitSeedSql(b.build(), { supersedes: sup?.build() });
}

/** Migration + rollback file paths for a seed slug (relative to the repo root). */
export function seedFilesFor(slug: string): { migration: string; rollback: string } {
  const b = SEED_BUILDERS[slug];
  if (!b) throw new Error(`unknown seed slug ${JSON.stringify(slug)} — known: ${Object.keys(SEED_BUILDERS).join(', ')}`);
  return {
    migration: `scripts/migrations/${b.ts}_regulation_tables_seed_${b.slugFile}.sql`,
    rollback: `scripts/rollback-${b.ts}-regulation-tables-seed-${b.slugFile.replace(/_/g, '-')}.sql`,
  };
}

if (process.argv[1]?.endsWith('emit-seed-sql.ts')) {
  // CLI: tsx scripts/regulation-tables/emit-seed-sql.ts <slug>
  const slug = process.argv[2] ?? '';
  const files = seedFilesFor(slug);
  const { up, down } = emitSeedSqlFor(slug);
  writeFileSync(files.migration, up);
  writeFileSync(files.rollback, down);
  console.log('wrote seed + rollback for', slug, '->', files.migration, files.rollback);
}
